import assert from 'node:assert/strict';
import {evaluateJob,mentionsHighVolumeAttention,roleFor} from '../career-assistant.mjs';
const preferences={priority_role:'administracion',favorite_tasks:'Tareas administrativas',avoid_tasks:'Atención constante a muchas personas; atención masiva al público'};
const job={title:'Analista administrativa',company:'Empresa de prueba',description_text:'Buscamos experiencia con Excel y control de facturación y planillas. Tareas administrativas de registro y validación.',language_status:'confirmed',geography_status:'confirmed',published_at:'2026-10-19T10:00:00Z',ats_found:['Excel','CRM'],salary_text:'ARS 1.700.000'};
const evidence=[{skill:'Excel',evidence:'Preparo y controlo las planillas de cupos en mi trabajo.',confirmed:true}];
const cvs=[{id:'cv-1',profile_type:'administracion',display_name:'CV Administrativo'}];
let result=evaluateJob(job,preferences,evidence,cvs);
assert.equal(result.rating,'Prioritaria','La administración debe ser prioridad');
assert.ok(result.verifiedKeywords.includes('Excel'));
assert.ok(result.unverifiedKeywords.includes('CRM'),'No inventar experiencia');
assert.equal(result.suggestedCVs[0]?.title,'CV Administrativo');
assert.ok(result.coverLetterIdeas.every(i=>!i.includes('Estimado/a')&&!i.includes('Me dirijo a')),'No redactar cartas');
assert.equal(roleFor('Asistente de back office'),'administracion');
assert.equal(roleFor('Analista de procesos'),'procesos');
assert.equal(roleFor('Soporte funcional'),'soporte_funcional');
const bulk={...job,title:'Customer Success',description_text:'Trabajar en call center; alto volumen de llamadas y consultas de clientes a diario'};
const c=evaluateJob(bulk,preferences,evidence,cvs);
assert.equal(c.highVolume,true,'Detectar atención masiva explícita');
assert.equal(c.rating,'Menor prioridad');
assert.ok(c.priority<result.priority);
const relational=evaluateJob({...bulk,description_text:'Gestionar cartera de tres clientes empresariales, renovaciones y seguimiento mensual'},preferences,evidence,cvs);
assert.equal(relational.highVolume,false,'No castigar todos los Customer Success automáticamente');
assert.notEqual(relational.rating,'No compatible');
const english=evaluateJob({...job,language_status:'excluded'},preferences,evidence,cvs);
assert.equal(english.rating,'No compatible');
assert.equal(english.priority,0);
const unknownGeo=evaluateJob({...job,geography_status:'pending'},preferences,evidence,cvs);
assert.equal(unknownGeo.rating,'Revisar requisitos');
assert.ok(unknownGeo.questionsToClarify.some(x=>x.includes('Argentina')));
const unconfirmed=evaluateJob(job,preferences,[{skill:'Excel',evidence:'Experiencia declarada pero sin confirmar',confirmed:false}],cvs);
assert.equal(unconfirmed.verifiedKeywords.length,0);
assert.ok(unconfirmed.unverifiedKeywords.includes('Excel'));
assert.equal(mentionsHighVolumeAttention('Administración','Gestión de registros y conciliaciones.'),false);
console.log('Asistente personal: 9 escenarios pasaron (administración, atención masiva, Customer Success, idioma, geografía, ATS, CV y carta).');
